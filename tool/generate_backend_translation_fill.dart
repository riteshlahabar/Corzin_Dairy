import 'dart:io';

void main() {
  final input = File('translation_import_exact_from_translations.csv');
  if (!input.existsSync()) {
    throw StateError('translation_import_exact_from_translations.csv not found');
  }

  final rows = _parseCsv(input.readAsStringSync());
  if (rows.isEmpty) {
    throw StateError('No rows found');
  }

  final header = rows.first;
  final output = <List<String>>[header];

  for (final row in rows.skip(1)) {
    if (row.length < 6) {
      output.add(row);
      continue;
    }

    final en = row[2].trim();
    final hi = row[3].trim().isEmpty ? _translateHi(en) : row[3].trim();
    final mr = row[4].trim().isEmpty ? _translateMr(en) : row[4].trim();

    output.add([
      row[0],
      row[1],
      row[2],
      hi,
      mr,
      row[5],
    ]);
  }

  final sink = StringBuffer()..write('\uFEFF');
  for (final row in output) {
    sink.writeln(row.map(_csv).join(','));
  }

  File('translation_import_dynamic_full.csv').writeAsStringSync(sink.toString());
  stdout.writeln('Generated: translation_import_dynamic_full.csv');
  stdout.writeln('Rows: ${output.length - 1}');
}


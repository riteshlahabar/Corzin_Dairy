String _translateGeneric(
  String text,
  Map<String, String> glossary,
  String pleaseWord,
  String selectWord,
  String enterWord,
  String updateWord,
) {
  if (text.isEmpty) return text;

  if (text.startsWith('Please enter valid ')) {
    final subject = _replaceGlossary(text.substring(19), glossary);
    return '$pleaseWord ??? $subject $enterWord';
  }
  if (text.startsWith('Please enter ')) {
    final subject = _replaceGlossary(text.substring(13), glossary);
    return '$pleaseWord $subject $enterWord';
  }
  if (text.startsWith('Please select ')) {
    final subject = _replaceGlossary(text.substring(14), glossary);
    return '$pleaseWord $subject $selectWord';
  }
  if (text.startsWith('Enter ')) {
    final subject = _replaceGlossary(text.substring(6), glossary);
    return '$subject $enterWord';
  }
  if (text.startsWith('Select ')) {
    final subject = _replaceGlossary(text.substring(7), glossary);
    return '$subject $selectWord';
  }
  if (text.startsWith('Choose ')) {
    final subject = _replaceGlossary(text.substring(7), glossary);
    return '$subject $selectWord';
  }
  if (text.startsWith('Failed to ')) {
    final subject = _replaceGlossary(text.substring(10), glossary);
    return '$subject ??? ????'.replaceAll('??? ????', glossary['__failed_suffix__'] ?? '??? ????');
  }
  if (text.startsWith('Unable to ')) {
    final subject = _replaceGlossary(text.substring(10), glossary);
    return '$subject ${glossary['__unable_suffix__'] ?? '???? ??? ??????'}';
  }
  if (text.startsWith('No ') && text.endsWith(' found')) {
    final subject = _replaceGlossary(text.substring(3, text.length - 6), glossary);
    return '$subject ${glossary['__not_found__'] ?? '???? ????'}';
  }
  if (text.endsWith(' updated successfully')) {
    final subject = _replaceGlossary(text.replaceAll(' updated successfully', ''), glossary);
    return '$subject ${glossary['__updated_success__'] ?? '??????????? ????? ???'}';
  }
  if (text.endsWith(' added successfully')) {
    final subject = _replaceGlossary(text.replaceAll(' added successfully', ''), glossary);
    return '$subject ${glossary['__added_success__'] ?? '??????????? ????? ???'}';
  }
  if (text.endsWith(' saved successfully')) {
    final subject = _replaceGlossary(text.replaceAll(' saved successfully', ''), glossary);
    return '$subject ${glossary['__saved_success__'] ?? '??????????? ??? ???'}';
  }

  return _replaceGlossary(text, glossary);
}

String _replaceGlossary(String text, Map<String, String> glossary) {
  var result = text;
  final keys = glossary.keys.where((key) => !key.startsWith('__')).toList()
    ..sort((a, b) => b.length.compareTo(a.length));
  for (final key in keys) {
    result = result.replaceAll(key, glossary[key]!);
  }
  return result;
}

String _csv(String value) => '"${value.replaceAll('"', '""')}"';

List<List<String>> _parseCsv(String input) {
  final rows = <List<String>>[];
  final currentRow = <String>[];
  final currentCell = StringBuffer();
  var inQuotes = false;

  for (var i = 0; i < input.length; i++) {
    final char = input[i];
    if (char == '"') {
      if (inQuotes && i + 1 < input.length && input[i + 1] == '"') {
        currentCell.write('"');
        i++;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }
    if (char == ',' && !inQuotes) {
      currentRow.add(currentCell.toString().replaceFirst('\uFEFF', ''));
      currentCell.clear();
      continue;
    }
    if ((char == '\n' || char == '\r') && !inQuotes) {
      if (char == '\r' && i + 1 < input.length && input[i + 1] == '\n') {
        i++;
      }
      currentRow.add(currentCell.toString().replaceFirst('\uFEFF', ''));
      currentCell.clear();
      if (currentRow.any((cell) => cell.isNotEmpty)) {
        rows.add(List<String>.from(currentRow));
      }
      currentRow.clear();
      continue;
    }
    currentCell.write(char);
  }

  if (currentCell.isNotEmpty || currentRow.isNotEmpty) {
    currentRow.add(currentCell.toString().replaceFirst('\uFEFF', ''));
    rows.add(List<String>.from(currentRow));
  }

  return rows;
}

